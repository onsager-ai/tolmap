//! `tolmap lens suggest` (issue #249): determinism, full resolution, hops
//! that agree with the route computation, the no-entry message and the CLI.
use std::path::Path;
use tolmap::lens::{self, HopSource, Lens, RouteKind, Routes};
use tolmap::lens_suggest::{self, Suggestions};
use tolmap::schema::MapDocument;

const FLASK: &str = include_str!("../data/flask.json");

fn flask() -> MapDocument {
    serde_json::from_str(FLASK).unwrap()
}

fn flask_suggestions() -> Suggestions {
    let source = lens_suggest::map_source(Path::new("data/flask.json"), FLASK.as_bytes());
    lens_suggest::suggest(&flask(), &source)
}

// Three districts; `main` is an entry that reaches `b` only through `a`'s
// hub. No bridge landmark; one road with a file edge, one without.
fn synthetic(entry: bool) -> MapDocument {
    let files = [
        ("src/a/main.py", 0, 0.0),
        ("src/a/hub.py", 0, 3.0),
        ("src/a/low.py", 0, 1.0),
        ("src/b/one.py", 1, 2.0),
        ("src/c/far.py", 2, 1.0),
    ];
    let nodes: Vec<_> = files
        .iter()
        .map(|&(_, d, fi)| serde_json::json!([d, 0.0, 0.0, 10, 1, 1, fi, 0.0, 0.0, 0.0, 0.0]))
        .collect();
    let district = |size| serde_json::json!({"size": size, "c": [0.0, 0.0], "blob": []});
    let mut landmarks = vec![serde_json::json!([1, "capital", "district 0 centre", 2])];
    if entry {
        landmarks.insert(0, serde_json::json!([0, "entry", "40 loc", 1]));
    }
    serde_json::from_value(serde_json::json!({
        "repo": "synthetic",
        "q": 0.3,
        "names": {"0": "a", "1": "b", "2": "c"},
        "districts": {"0": district(3), "1": district(1), "2": district(1)},
        "F": files.iter().map(|f| f.0).collect::<Vec<_>>(),
        "N": nodes,
        "E": [[0, 1], [0, 2], [1, 3]],
        "L": landmarks,
        "S": {},
        "U": {},
        "roads": [[0, 1, 2.0], [0, 2, 1.0]],
        "lang": "python"
    }))
    .unwrap()
}

fn names(s: &Suggestions) -> Vec<&str> {
    s.lenses.iter().map(|(n, _)| n.as_str()).collect()
}

// Every suggestion parses, resolves with nothing unresolved, has only
// computed hops, and each hop is the route `Routes::find` gives for its
// endpoints, found by following imports.
fn assert_sound(s: &Suggestions, map: &MapDocument) {
    let routes = Routes::new(map);
    let index = |p: &str| map.files.iter().position(|f| f == p).unwrap();
    for (name, text) in &s.lenses {
        assert!(
            text.starts_with("# Generated by `tolmap lens suggest`"),
            "{name}"
        );
        assert!(text.contains("lower bound"), "{name}");
        assert!(!text.contains("declared"), "{name}");
        let lens = Lens::parse(text).unwrap();
        assert!(
            lens.title.as_deref().unwrap().contains("generated"),
            "{name}"
        );
        let report = lens::resolve(&lens, map);
        assert!(
            report.unresolved.is_empty(),
            "{name}: {:?}",
            report.unresolved
        );
        for path in &report.paths {
            for hop in &path.hops {
                assert_eq!(hop.source, HopSource::Computed);
                assert_eq!(
                    hop.edge_kind,
                    Some(RouteKind::Imports),
                    "{name} {}",
                    path.name
                );
                let (a, b) = (&path.stops[hop.from].spec, &path.stops[hop.to].spec);
                let (files, kind) = routes.find(index(a), index(b)).unwrap();
                assert_eq!(kind, RouteKind::Imports);
                let via: Vec<&str> = files.iter().map(|&f| map.files[f].as_str()).collect();
                assert_eq!(hop.via, via);
            }
        }
    }
}

#[test]
fn flask_suggestions_are_deterministic_and_resolve_fully() {
    let map = flask();
    let before = serde_json::to_vec(&map).unwrap();
    let first = flask_suggestions();
    let second = flask_suggestions();
    assert_eq!(first.lenses, second.lenses);
    assert_eq!(before, serde_json::to_vec(&map).unwrap());
    assert_eq!(
        names(&first),
        ["entry-routes", "district-tour", "crossings"]
    );
    assert!(first.messages.is_empty(), "{:?}", first.messages);
    assert_sound(&first, &map);

    let entry = Lens::parse(&first.lenses[0].1).unwrap();
    assert_eq!(entry.paths.len(), 2);
    let ends: Vec<&str> = entry
        .paths
        .iter()
        .map(|p| p.stops.last().unwrap().at.as_str())
        .collect();
    // Both entries reach another district.
    assert_eq!(ends, ["src/flask/wrappers.py", "src/flask/globals.py"]);

    let tour = Lens::parse(&first.lenses[1].1).unwrap();
    assert_eq!(tour.areas.len(), map.names.len());
    let members: usize = tour.areas.iter().map(|a| a.members.len()).sum();
    assert_eq!(members, map.files.len());
    assert_eq!(tour.notes.len(), 3);
}

#[test]
fn no_entry_landmark_gives_a_message_not_an_empty_file() {
    let with = lens_suggest::suggest(&synthetic(true), "synthetic.json");
    assert_eq!(names(&with), ["entry-routes", "district-tour", "crossings"]);
    assert_sound(&with, &synthetic(true));
    let entry = Lens::parse(&with.lenses[0].1).unwrap();
    let stops: Vec<&str> = entry.paths[0].stops.iter().map(|s| s.at.as_str()).collect();
    assert_eq!(stops, ["src/a/main.py", "src/a/hub.py", "src/b/one.py"]);
    // The road a – c has no file edge: reported, not drawn.
    assert!(
        with.messages.iter().any(|m| m.contains("road a – c")),
        "{:?}",
        with.messages
    );

    let without = lens_suggest::suggest(&synthetic(false), "synthetic.json");
    assert_eq!(names(&without), ["district-tour", "crossings"]);
    assert!(without
        .messages
        .iter()
        .any(|m| m == "no entry landmark in the map: entry-routes not written"));
    assert_sound(&without, &synthetic(false));
}

#[test]
fn cli_writes_only_into_out() {
    let dir = tempfile::tempdir().unwrap();
    let map = concat!(env!("CARGO_MANIFEST_DIR"), "/data/flask.json");
    let run = |extra: &[&std::ffi::OsStr]| {
        std::process::Command::new(env!("CARGO_BIN_EXE_tolmap"))
            .current_dir(dir.path())
            .args(["lens", "suggest", "--map", map])
            .args(extra)
            .output()
            .unwrap()
    };
    let printed = run(&[]);
    assert_eq!(printed.status.code(), Some(0));
    assert_eq!(std::fs::read_dir(dir.path()).unwrap().count(), 0);
    let stdout = String::from_utf8(printed.stdout).unwrap();
    assert!(stdout.starts_with("# ==> entry-routes.toml <==\n"));

    let out = dir.path().join("lenses");
    let written = run(&[std::ffi::OsStr::new("--out"), out.as_os_str()]);
    assert_eq!(written.status.code(), Some(0));
    // The header names the map by file name and hash, not the typed path.
    for (name, text) in flask_suggestions().lenses {
        let file = std::fs::read_to_string(out.join(format!("{name}.toml"))).unwrap();
        assert_eq!(file, text, "{name}");
    }

    let bad = std::process::Command::new(env!("CARGO_BIN_EXE_tolmap"))
        .args(["lens", "suggest", "--map"])
        .arg(dir.path().join("absent.json"))
        .output()
        .unwrap();
    assert_eq!(bad.status.code(), Some(2));
}
